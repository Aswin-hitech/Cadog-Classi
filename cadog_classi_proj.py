"""
Development of a Convolutional Neural Network (CNN) for
Dog-Cat Image Classification Using Three Convolutional Layers
"""

import os
import json
import random
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import seaborn as sns
import tensorflow as tf
import kagglehub

from tensorflow import keras
from tensorflow.keras import layers
from sklearn.metrics import (
    classification_report,
    confusion_matrix,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
    balanced_accuracy_score,
    matthews_corrcoef,
)

# ---------------- CONFIGURATION ---------------- #

DATASET_ID = "aleemaparakatta/cats-and-dogs-mini-dataset"
OUTPUT_DIR = Path("outputs")

IMAGE_SIZE = (160, 160)
BATCH_SIZE = 32
EPOCHS = 30
LEARNING_RATE = 0.001
DROPOUT_RATE = 0.4
VALIDATION_SPLIT = 0.2
RANDOM_SEED = 42

random.seed(RANDOM_SEED)
np.random.seed(RANDOM_SEED)
tf.random.set_seed(RANDOM_SEED)

OUTPUT_DIR.mkdir(parents=True, exist_ok=True)


# ---------------- IMPORT DATASET ---------------- #

print("Downloading dataset...")
dataset_path = Path(kagglehub.dataset_download(DATASET_ID))
print("Dataset path:", dataset_path)


def find_split(root, names):
    for path in [root] + list(root.rglob("*")):
        if path.is_dir() and path.name.lower() in names:
            subdirs = [p for p in path.iterdir() if p.is_dir()]
            if len(subdirs) >= 2:
                return path
    return None


train_dir = find_split(dataset_path, {"train", "training"})
test_dir = find_split(
    dataset_path, {"test", "testing", "valid", "validation"}
)

common_args = {
    "image_size": IMAGE_SIZE,
    "batch_size": BATCH_SIZE,
    "label_mode": "binary",
    "seed": RANDOM_SEED,
}

if train_dir is None:
    class_dirs = [p for p in dataset_path.iterdir() if p.is_dir()]
    if len(class_dirs) < 2:
        raise FileNotFoundError(
            "Could not locate class folders for cats and dogs."
        )
    train_dir = dataset_path

# Use a separate test split if available; otherwise split training data.
if test_dir is not None:
    train_ds = keras.utils.image_dataset_from_directory(
        train_dir,
        validation_split=VALIDATION_SPLIT,
        subset="training",
        shuffle=True,
        **common_args
    )

    val_ds = keras.utils.image_dataset_from_directory(
        test_dir,
        image_size=IMAGE_SIZE,
        batch_size=BATCH_SIZE,
        label_mode="binary",
        shuffle=False
    )
else:
    train_ds = keras.utils.image_dataset_from_directory(
        train_dir,
        validation_split=VALIDATION_SPLIT,
        subset="training",
        shuffle=True,
        **common_args
    )

    val_ds = keras.utils.image_dataset_from_directory(
        train_dir,
        validation_split=VALIDATION_SPLIT,
        subset="validation",
        shuffle=False,
        **common_args
    )

class_names = train_ds.class_names

if test_dir is not None and class_names != val_ds.class_names:
    raise ValueError("Training and test class folders do not match.")

print("Classes:", class_names)

train_ds = train_ds.cache().shuffle(
    1000, seed=RANDOM_SEED
).prefetch(tf.data.AUTOTUNE)

val_ds = val_ds.cache().prefetch(tf.data.AUTOTUNE)


# ---------------- DATA AUGMENTATION ---------------- #

augmentation = keras.Sequential([
    layers.RandomFlip("horizontal"),
    layers.RandomRotation(0.08),
    layers.RandomZoom(0.1),
    layers.RandomContrast(0.1)
], name="data_augmentation")


# ---------------- BUILD THREE-LAYER CNN ---------------- #

regularizer = keras.regularizers.l2(0.0001)

model = keras.Sequential([
    layers.Input(shape=(160, 160, 3)),
    augmentation,
    layers.Rescaling(1.0 / 255),

    # Convolutional Layer 1
    layers.Conv2D(
        32, (3, 3), padding="same",
        activation="relu",
        kernel_regularizer=regularizer
    ),
    layers.BatchNormalization(),
    layers.MaxPooling2D((2, 2)),

    # Convolutional Layer 2
    layers.Conv2D(
        64, (3, 3), padding="same",
        activation="relu",
        kernel_regularizer=regularizer
    ),
    layers.BatchNormalization(),
    layers.MaxPooling2D((2, 2)),

    # Convolutional Layer 3
    layers.Conv2D(
        128, (3, 3), padding="same",
        activation="relu",
        kernel_regularizer=regularizer
    ),
    layers.BatchNormalization(),
    layers.MaxPooling2D((2, 2)),

    # Classification layers
    layers.GlobalAveragePooling2D(),
    layers.Dense(128, activation="relu"),
    layers.Dropout(DROPOUT_RATE),
    layers.Dense(1, activation="sigmoid")
], name="Dog_Cat_CNN")

model.compile(
    optimizer=keras.optimizers.Adam(
        learning_rate=LEARNING_RATE
    ),
    loss="binary_crossentropy",
    metrics=[
        "accuracy",
        keras.metrics.Precision(name="precision"),
        keras.metrics.Recall(name="recall"),
        keras.metrics.AUC(name="auc")
    ]
)

model.summary()

with open(OUTPUT_DIR / "model_summary.txt", "w") as f:
    model.summary(print_fn=lambda line: f.write(line + "\n"))


# ---------------- TRAIN MODEL ---------------- #

callbacks = [
    keras.callbacks.EarlyStopping(
        monitor="val_loss",
        patience=5,
        restore_best_weights=True,
        verbose=1
    ),
    keras.callbacks.ReduceLROnPlateau(
        monitor="val_loss",
        factor=0.5,
        patience=2,
        min_lr=1e-6,
        verbose=1
    ),
    keras.callbacks.ModelCheckpoint(
        str(OUTPUT_DIR / "best_dog_cat_cnn.keras"),
        monitor="val_loss",
        save_best_only=True,
        verbose=1
    )
]

history = model.fit(
    train_ds,
    validation_data=val_ds,
    epochs=EPOCHS,
    callbacks=callbacks
)


# ---------------- ACCURACY GRAPH ---------------- #

epochs_range = range(1, len(history.history["accuracy"]) + 1)

plt.figure(figsize=(9, 6))
plt.plot(
    epochs_range, history.history["accuracy"],
    label="Training Accuracy"
)
plt.plot(
    epochs_range, history.history["val_accuracy"],
    label="Validation Accuracy"
)
plt.title("CNN Model Accuracy")
plt.xlabel("Epoch")
plt.ylabel("Accuracy")
plt.legend()
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.savefig(OUTPUT_DIR / "accuracy_graph.png", dpi=160)
plt.close()


# ---------------- LOSS GRAPH ---------------- #

plt.figure(figsize=(9, 6))
plt.plot(
    epochs_range, history.history["loss"],
    label="Training Loss"
)
plt.plot(
    epochs_range, history.history["val_loss"],
    label="Validation Loss"
)
plt.title("CNN Model Loss")
plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.legend()
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.savefig(OUTPUT_DIR / "loss_graph.png", dpi=160)
plt.close()


# ---------------- AUC GRAPH ---------------- #

plt.figure(figsize=(9, 6))
plt.plot(
    epochs_range, history.history["auc"],
    label="Training AUC"
)
plt.plot(
    epochs_range, history.history["val_auc"],
    label="Validation AUC"
)
plt.title("CNN Model AUC")
plt.xlabel("Epoch")
plt.ylabel("AUC")
plt.legend()
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.savefig(OUTPUT_DIR / "auc_graph.png", dpi=160)
plt.close()


# ---------------- CONFUSION MATRIX ---------------- #

y_true = []
y_prob = []

for images, labels in val_ds:
    probabilities = model.predict(images, verbose=0).ravel()
    y_prob.extend(probabilities)
    y_true.extend(labels.numpy().ravel().astype(int))

y_true = np.array(y_true)
y_prob = np.array(y_prob)
y_pred = (y_prob >= 0.5).astype(int)

cm = confusion_matrix(y_true, y_pred, labels=[0, 1])

plt.figure(figsize=(7, 6))
sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="Blues",
    xticklabels=class_names,
    yticklabels=class_names
)
plt.title("Confusion Matrix")
plt.xlabel("Predicted Class")
plt.ylabel("Actual Class")
plt.tight_layout()
plt.savefig(OUTPUT_DIR / "confusion_matrix.png", dpi=160)
plt.close()


def compute_additional_metrics(true_labels, predicted_labels, predicted_probs):
    tn, fp, fn, tp = confusion_matrix(
        true_labels, predicted_labels, labels=[0, 1]
    ).ravel()

    total = tp + tn + fp + fn
    precision = tp / (tp + fp) if (tp + fp) else 0.0
    recall = tp / (tp + fn) if (tp + fn) else 0.0
    specificity = tn / (tn + fp) if (tn + fp) else 0.0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) else 0.0
    false_positive_rate = fp / (fp + tn) if (fp + tn) else 0.0
    false_negative_rate = fn / (fn + tp) if (fn + tp) else 0.0
    balanced_acc = (recall + specificity) / 2.0

    mcc_denominator = np.sqrt((tp + fp) * (tp + fn) * (tn + fp) * (tn + fn))
    mcc = (tp * tn - fp * fn) / mcc_denominator if mcc_denominator else 0.0

    corr = np.corrcoef(true_labels.astype(float), predicted_probs)[0, 1]
    if np.isnan(corr):
        corr = 0.0

    return {
        "accuracy": (tp + tn) / total if total else 0.0,
        "precision": float(precision),
        "recall": float(recall),
        "sensitivity": float(recall),
        "specificity": float(specificity),
        "f1_score": float(f1),
        "balanced_accuracy": float(balanced_acc),
        "false_positive_rate": float(false_positive_rate),
        "false_negative_rate": float(false_negative_rate),
        "matthews_corrcoef": float(mcc),
        "roc_auc": float(roc_auc_score(true_labels, predicted_probs)),
        "pearson_correlation": float(corr),
        "youden_j_statistic": float(recall + specificity - 1.0),
        "support": int(total),
    }


# ---------------- EVALUATION ---------------- #

evaluation = model.evaluate(val_ds, verbose=0, return_dict=True)

print("\nEvaluation Results:")
for metric, value in evaluation.items():
    print(f"{metric}: {value:.4f}")

report = classification_report(
    y_true,
    y_pred,
    labels=[0, 1],
    target_names=class_names,
    output_dict=True,
    zero_division=0
)

additional_metrics = compute_additional_metrics(y_true, y_pred, y_prob)

print("\nClassification Report:")
print(classification_report(
    y_true,
    y_pred,
    labels=[0, 1],
    target_names=class_names,
    zero_division=0
))

print("\nAdditional Metrics:")
for metric, value in additional_metrics.items():
    print(f"{metric}: {value:.6f}")

with open(OUTPUT_DIR / "classification_report.json", "w") as f:
    json.dump(report, f, indent=2)

with open(OUTPUT_DIR / "evaluation_metrics.json", "w") as f:
    json.dump({
        "class_names": class_names,
        "metrics": {
            **{
                key: float(value)
                for key, value in evaluation.items()
            },
            **additional_metrics,
        },
        "confusion_matrix": cm.tolist()
    }, f, indent=2)


# ---------------- SAVE MODEL ---------------- #

model.save(OUTPUT_DIR / "dog_cat_cnn_final.keras")

with open(OUTPUT_DIR / "configuration.json", "w") as f:
    json.dump({
        "dataset": DATASET_ID,
        "image_size": IMAGE_SIZE,
        "batch_size": BATCH_SIZE,
        "epochs_configured": EPOCHS,
        "epochs_completed": len(history.history["loss"]),
        "learning_rate": LEARNING_RATE,
        "optimizer": "Adam",
        "loss": "binary_crossentropy",
        "convolutional_layers": 3,
        "filters": [32, 64, 128],
        "dropout": DROPOUT_RATE,
        "random_seed": RANDOM_SEED,
        "classes": class_names
    }, f, indent=2)

print("\nTraining and evaluation completed.")
print("All graphs, reports and models saved in:", OUTPUT_DIR.resolve())
